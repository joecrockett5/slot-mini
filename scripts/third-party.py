#!/usr/bin/env python3
"""Write the licences of every crate compiled into a shipped binary.

    scripts/third-party.py <out file>          the Miyoo's slot-mini
    scripts/third-party.py --pc <out file>     the Windows slot-mini-pc

Walks `cargo metadata` from the package's normal and build dependencies for
its target and copies each crate's own LICENSE/COPYING/NOTICE files from
its source directory, with its name, version and licence expression.
"""
import json
import os
import subprocess
import sys

args = sys.argv[1:]
pc = "--pc" in args
out = [a for a in args if a != "--pc"][0]
package = "slot-mini-pc" if pc else "slot-mini"
platform = "x86_64-pc-windows-msvc" if pc else "armv7-unknown-linux-musleabihf"
meta = json.loads(subprocess.check_output([
    "cargo", "metadata", "--format-version", "1",
    "--filter-platform", platform,
]))
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
pkgs = {p["id"]: p for p in meta["packages"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == package)
seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])
ours = {"slot-mini", "slot-mini-gfx", "slot-mini-pc", "slot-mini-store", "slot-mini-ui"}
crates = sorted((pkgs[i] for i in seen if pkgs[i]["name"] not in ours), key=lambda p: p["name"])
with open(out, "w") as f:
    f.write(f"Third-party Rust crates compiled into {package}, with their licences.\n")
    f.write("Generated by scripts/third-party.py.\n\n")
    for p in crates:
        f.write(f"- {p['name']} {p['version']}: {p.get('license') or 'see below'}\n")
    for p in crates:
        d = os.path.dirname(p["manifest_path"])
        files = sorted(n for n in os.listdir(d)
                       if n.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")))
        f.write("\n" + "=" * 78 + f"\n{p['name']} {p['version']} ({p.get('license') or '?'})\n")
        if p.get("repository"):
            f.write(p["repository"] + "\n")
        f.write("=" * 78 + "\n")
        for n in files:
            path = os.path.join(d, n)
            if os.path.isfile(path):
                f.write(f"\n--- {n} ---\n\n")
                f.write(open(path, encoding="utf-8", errors="replace").read())
        if not files:
            f.write("\n(No licence file in the published crate; licence expression above.)\n")
print(f"{len(crates)} crates -> {out}")
